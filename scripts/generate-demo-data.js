'use strict';

// Writes the deterministic demo files and the expected-outcomes note into demo-data/.
const fs = require('node:fs');
const path = require('node:path');
const { generateDemo } = require('./lib/demo-data');

const out = path.join(__dirname, '..', 'demo-data');
const { ledgerCsv, settlementCsv, expected } = generateDemo();
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'ledger-2026-11.csv'), ledgerCsv);
fs.writeFileSync(path.join(out, 'nimbuspay-settlement-2026-11.csv'), settlementCsv);

const e = expected;
const types = Object.entries(e.breaksByType).map(([t, n]) => `| ${t} | ${n} |`).join('\n');
fs.writeFileSync(path.join(out, 'expected-outcomes.md'), `# Expected outcomes for the demo files

Generated by \`npm run demo:generate\` (deterministic; do not edit by hand). These figures are what the
generator *constructed*, so they act as ground truth for the reconciliation engine. A test
(\`test/integration/demo-data.test.js\`) re-generates the files and checks the engine against them.

Run configuration: default settings (2-day settlement window, 2% fee, ₹0.01 fee tolerance, no amount
tolerance), as-of date **${e.asOfDate}**.

## Upload

| File | Rows | Accepted | Rejected |
|---|---:|---:|---:|
| \`ledger-2026-11.csv\` | ${e.ledgerRows.total} | ${e.ledgerRows.accepted} | ${e.ledgerRows.rejected} |
| \`nimbuspay-settlement-2026-11.csv\` | ${e.settlementRows.total} | ${e.settlementRows.accepted} | ${e.settlementRows.rejected} |

Rejected ledger rows: zero amount, currency USD, three decimal places, timestamp without a UTC offset.
Rejected settlement rows: refund with a positive amount, repeated \`line_id\`, impossible date.

## Reconciliation result

| Outcome | Count |
|---|---:|
| Transactions matched | ${e.transactions.matched} |
| Awaiting settlement (pending) | ${e.transactions.pending} |
| Transaction breaks | ${e.transactions.breaks} |
| Batches reconciled | ${e.batches.matched} of ${e.batches.total} |

| Break type | Count |
|---|---:|
${types}

Total breaks in the queue: **${e.totalBreaks}** (${e.transactions.breaks} transaction + ${e.batches.broken} batch).

## What was injected

* 260 clean matches, 2 payments on the IST midnight boundary, and 5 small-amount payments whose 2% fee falls exactly on half a paisa (rounds up).
* 12 refunds (ledger \`REFUND\` with a positive amount, settlement with a negative amount).
* 3 references that legitimately appear twice on both sides with identical amounts (matched in file order).
* 8 amount mismatches, including a one-paisa difference.
* 6 transactions settled twice (one match plus one duplicate break each).
* 6 fee variances, 5 settlement lines with no ledger record, 7 entries missing after the window.
* 14 entries recorded 6–8 Nov that are still inside their settlement window (pending).
* 2 ambiguous references (two ledger amounts, one settlement amount equal to neither): 3 breaks each.
* 2 batches whose declared totals disagree with their lines (${e.batches.brokenIds.join(', ')}).
`);
console.log(`Wrote demo-data/ (${e.ledgerRows.total} ledger rows, ${e.settlementRows.total} settlement rows).`);
